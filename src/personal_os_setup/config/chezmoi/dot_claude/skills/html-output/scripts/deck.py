#!/usr/bin/env python3
"""Create, refresh and check offline HTML presentations with the standard library."""

import argparse
from collections import Counter
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import shutil
import sys
from urllib.parse import unquote, urlsplit


TEMPLATE = Path(__file__).resolve().parent.parent / "assets" / "deck-template"
RUNTIME = ("theme.css", "player.js")
CONTROLS = {
    "deck", "viewport", "overview", "toolbar", "counter", "previous", "next",
    "progress", "notes-button", "overview-button", "fullscreen", "print", "help",
    "help-button", "close-help", "announcement", "layout-status",
}


class DeckParser(HTMLParser):
    """Collect portable resource references and the player contract."""

    def __init__(self):
        super().__init__()
        self.ids = []
        self.references = []
        self.slides = 0
        self.config = {}
        self.errors = []
        self.markers = []
        self.slide_contracts = []
        self.current_slide = None
        self.section_depth = 0
        self.slide_depth = 0

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        classes = (attrs.get("class") or "").split()
        if tag == "section":
            self.section_depth += 1
        if attrs.get("id"):
            self.ids.append(attrs["id"])
        if "slide" in classes:
            self.slides += 1
            if self.current_slide is not None:
                self.errors.append("Slides must not be nested")
            self.current_slide = {"h1": 0, "content": 0, "notes": 0, "chrome": 0}
            self.slide_contracts.append(self.current_slide)
            self.slide_depth = self.section_depth
            if tag != "section":
                self.errors.append("Each slide must be a section element")
        if self.current_slide is not None:
            if tag == "h1":
                self.current_slide["h1"] += 1
            if "content" in classes:
                self.current_slide["content"] += 1
            if "notes" in classes:
                self.current_slide["notes"] += 1
            if tag == "footer" or "brand" in classes:
                self.current_slide["chrome"] += 1
        if attrs.get("id") == "deck":
            self.config = attrs
        if tag in {"img", "script", "source"} and attrs.get("src"):
            self.references.append(attrs["src"])
        if tag == "link" and attrs.get("href"):
            self.references.append(attrs["href"])
        if tag == "img" and "alt" not in attrs:
            self.errors.append("An image is missing its alt attribute")
        if attrs.get("marker-end"):
            self.markers.append(attrs["marker-end"])

    handle_startendtag = handle_starttag

    def handle_endtag(self, tag):
        if tag == "section":
            if self.section_depth == self.slide_depth:
                self.current_slide = None
            self.section_depth -= 1


def local_resource(root, reference):
    parts = urlsplit(reference)
    if parts.scheme or parts.netloc or not parts.path:
        raise ValueError(f"Resource must be a relative local file: {reference}")
    path = (root / unquote(parts.path)).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError(f"Resource escapes the deck directory: {reference}")
    if not path.is_file():
        raise ValueError(f"Missing local resource: {reference}")
    return path


def check(root, require_current_runtime=False):
    html = root / "index.html"
    if not html.is_file():
        raise ValueError(f"Missing presentation: {html}")
    parser = DeckParser()
    parser.feed(html.read_text(encoding="utf-8"))
    errors = parser.errors
    if not parser.slides:
        errors.append("No slides found")
    for index, contract in enumerate(parser.slide_contracts, 1):
        for name in ("h1", "content", "notes"):
            if contract[name] != 1:
                errors.append(f"Slide {index} needs exactly one {name} element")
        if contract["chrome"]:
            errors.append(f"Slide {index} repeats branding or a footer generated by the player")
    for value, count in Counter(parser.ids).items():
        if count > 1:
            errors.append(f"Duplicate id: {value}")
    for missing in sorted(CONTROLS - set(parser.ids)):
        errors.append(f"Missing player control: {missing}")
    references = parser.references + ([parser.config["data-logo"]] if parser.config.get("data-logo") else [])
    for reference in references:
        try:
            resource = local_resource(root, reference)
            if resource.suffix == ".css":
                css = resource.read_text(encoding="utf-8")
                if re.search(r"@import\b", css):
                    errors.append(f"CSS imports hide dependencies: {resource.name}")
                for url in re.findall(r"url\(\s*['\"]?([^'\")\s]+)", css):
                    if not url.startswith(("data:", "#")):
                        local_resource(resource.parent, url)
        except ValueError as error:
            errors.append(str(error))
    for marker in parser.markers:
        match = re.fullmatch(r"url\(#([^)]*)\)", marker)
        if not match or match[1] not in parser.ids:
            errors.append(f"Missing SVG arrow marker: {marker}")
    for key in ("data-team", "data-footer", "data-min-scale"):
        if not parser.config.get(key):
            errors.append(f"Missing deck setting: {key}")
    try:
        if not 0.85 <= float(parser.config.get("data-min-scale", "0")) <= 1:
            errors.append("data-min-scale must be between 0.85 and 1")
    except ValueError:
        errors.append("data-min-scale must be a number")
    if require_current_runtime:
        for name in RUNTIME:
            target = root / name
            if not target.is_file() or target.read_bytes() != (TEMPLATE / name).read_bytes():
                errors.append(f"Shared {name} differs. Run deck.py sync to refresh it.")
    result = {"slides": parser.slides, "localResources": len(set(references)), "errors": errors}
    print(json.dumps(result, indent=2))
    return not errors


def create(args):
    destination = args.destination.resolve()
    # Refuse to overwrite an existing deck, including untracked files.
    if destination.exists():
        raise ValueError(f"Destination already exists: {destination}")
    custom_logo = None
    if args.logo:
        custom_logo = args.logo.resolve()
        if custom_logo.suffix.lower() not in {".png", ".svg", ".webp", ".jpg", ".jpeg"} or not custom_logo.is_file():
            raise ValueError("--logo must name an existing PNG, SVG, WebP or JPEG")
    shutil.copytree(TEMPLATE, destination)
    (destination / "assets").mkdir(exist_ok=True)
    html = (destination / "index.html").read_text(encoding="utf-8")
    html = re.sub(r"<title>.*?</title>", lambda _: f"<title>{escape(args.title)}</title>", html)
    html = re.sub(r"<h1>.*?</h1>", lambda _: f"<h1>{escape(args.title)}</h1>", html, count=1, flags=re.S)
    html = re.sub(r'name="description" content="[^"]*"', lambda _: f'name="description" content="{escape(args.title, quote=True)}"', html)
    settings = {"team": args.team, "footer": args.footer or args.title}
    if custom_logo:
        name = "team-logo" + custom_logo.suffix.lower()
        shutil.copyfile(custom_logo, destination / "assets" / name)
        settings.update({"logo": f"assets/{name}", "logo-alt": args.team})
    for key, value in settings.items():
        html = re.sub(rf'data-{key}="[^"]*"', lambda _, value=value, key=key: f'data-{key}="{escape(value, quote=True)}"', html)
    (destination / "index.html").write_text(html, encoding="utf-8")
    print(f"Created {destination / 'index.html'}")
    return check(destination, require_current_runtime=True)


def sync(args):
    if not (args.destination / "index.html").is_file():
        raise ValueError("sync requires an existing deck directory")
    for name in RUNTIME:
        target = args.destination / name
        if target.is_symlink():
            raise ValueError(f"Refusing to replace a runtime symlink: {target}")
        if target.resolve() == (TEMPLATE / name).resolve():
            continue
        shutil.copyfile(TEMPLATE / name, target)
    print("Refreshed shared theme and player. Slide content, deck.css and logos were preserved.")
    return check(args.destination, require_current_runtime=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    new = commands.add_parser("new", help="Copy a portable layout starter into a new directory")
    new.add_argument("destination", type=Path)
    new.add_argument("--title", required=True)
    new.add_argument("--team", default="Presentation")
    new.add_argument("--footer")
    new.add_argument("--logo", type=Path)
    refresh = commands.add_parser("sync", help="Refresh only an existing deck's shared theme/player")
    refresh.add_argument("destination", type=Path)
    verify = commands.add_parser("check", help="Check local dependencies, ids, settings and player controls")
    verify.add_argument("destination", type=Path)
    verify.add_argument("--runtime", action="store_true", help="Also detect shared engine drift")
    args = parser.parse_args()
    try:
        passed = create(args) if args.command == "new" else sync(args) if args.command == "sync" else check(args.destination, args.runtime)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
